// Config plugin: keep the app's data out of Android backups AND device-to-device transfers.
//
// `android:allowBackup="false"` (app.json) stops cloud backup, but on Android 12+ (targetSdk 31+)
// it does NOT stop device-to-device migration: that is governed only by
// `android:dataExtractionRules`. This plugin writes
//   res/xml/data_extraction_rules.xml  (Android 12+: <cloud-backup> and <device-transfer>)
//   res/xml/backup_rules.xml           (android:fullBackupContent, Android 11 / API 30 and lower)
// both excluding every domain, and points <application> at them.

const fs = require('node:fs');
const path = require('node:path');

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/** Every storage domain the backup / data-extraction XML formats know about. */
const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

const DATA_EXTRACTION_RULES = 'data_extraction_rules';
const BACKUP_RULES = 'backup_rules';

function excludes(indent) {
  return DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" path="." />`).join('\n');
}

/** res/xml/data_extraction_rules.xml (API 31+): nothing is backed up or transferred. */
function dataExtractionRulesXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withNoBackupRules.js: no app data in cloud backup or device transfer. -->',
    '<data-extraction-rules>',
    '  <cloud-backup>',
    excludes('    '),
    '  </cloud-backup>',
    '  <device-transfer>',
    excludes('    '),
    '  </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');
}

/** res/xml/backup_rules.xml (android:fullBackupContent, API <= 30): nothing is backed up. */
function backupRulesXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withNoBackupRules.js: no app data in backups (API 30 and lower). -->',
    '<full-backup-content>',
    excludes('  '),
    '</full-backup-content>',
    '',
  ].join('\n');
}

/**
 * Pure transform of the parsed AndroidManifest (xml2js shape used by `withAndroidManifest`):
 * sets `android:dataExtractionRules` and `android:fullBackupContent` on <application>.
 * Idempotent (same values on every run).
 *
 * @param {import('expo/config-plugins').AndroidConfig.Manifest.AndroidManifest} manifest
 */
function setNoBackupRules(manifest) {
  const application = manifest.manifest.application?.[0];
  if (application === undefined) {
    throw new Error('withNoBackupRules: <application> not found in AndroidManifest.xml');
  }
  application.$ = {
    ...application.$,
    'android:dataExtractionRules': `@xml/${DATA_EXTRACTION_RULES}`,
    'android:fullBackupContent': `@xml/${BACKUP_RULES}`,
  };
  return manifest;
}

/** Writes both XML resources under `<platformProjectRoot>/app/src/main/res/xml/`. */
function writeRuleFiles(platformProjectRoot) {
  const dir = path.join(platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${DATA_EXTRACTION_RULES}.xml`), dataExtractionRulesXml());
  fs.writeFileSync(path.join(dir, `${BACKUP_RULES}.xml`), backupRulesXml());
}

/** @type {import('expo/config-plugins').ConfigPlugin} */
function withNoBackupRules(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      writeRuleFiles(cfg.modRequest.platformProjectRoot);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    cfg.modResults = setNoBackupRules(cfg.modResults);
    return cfg;
  });
}

module.exports = withNoBackupRules;
module.exports.DOMAINS = DOMAINS;
module.exports.dataExtractionRulesXml = dataExtractionRulesXml;
module.exports.backupRulesXml = backupRulesXml;
module.exports.setNoBackupRules = setNoBackupRules;
module.exports.writeRuleFiles = writeRuleFiles;
